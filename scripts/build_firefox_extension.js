/**
 * TORI Download Manager — Firefox Extension Build & Package Pipeline
 * 
 * - Copies shared assets (scripts, styles, popup, options, icons) from extension/ to extension/firefox/
 * - Validates Firefox Manifest V3 with Mozilla's web-ext linter
 * - Produces release package in release/v1.0.1-firefox-candidate/
 * - Computes SHA-256 checksums and prepares AMO submission metadata
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const EXT_SRC = path.join(ROOT, 'extension');
const FF_DIR = path.join(EXT_SRC, 'firefox');
const CANDIDATE_DIR = path.join(ROOT, 'release', 'v1.0.1-firefox-candidate');

function copyRecursive(src, dest) {
  const stat = fs.statSync(src);
  if (stat.isDirectory()) {
    if (!fs.existsSync(dest)) fs.mkdirSync(dest, { recursive: true });
    for (const child of fs.readdirSync(src)) {
      copyRecursive(path.join(src, child), path.join(dest, child));
    }
  } else {
    fs.copyFileSync(src, dest);
  }
}

function run() {
  console.log('=== TORI v1.0.1: Firefox Extension Build & Packaging ===\n');

  if (!fs.existsSync(FF_DIR)) {
    fs.mkdirSync(FF_DIR, { recursive: true });
  }

  // Ensure candidate directory exists
  if (!fs.existsSync(CANDIDATE_DIR)) {
    fs.mkdirSync(CANDIDATE_DIR, { recursive: true });
  }

  console.log('[1] Syncing shared extension components into extension/firefox/...');
  const sharedFiles = ['background.js', 'content.js', 'content.css'];
  for (const f of sharedFiles) {
    fs.copyFileSync(path.join(EXT_SRC, f), path.join(FF_DIR, f));
    console.log(`    Synced: ${f}`);
  }

  const sharedDirs = ['popup', 'options', 'icons'];
  for (const d of sharedDirs) {
    copyRecursive(path.join(EXT_SRC, d), path.join(FF_DIR, d));
    console.log(`    Synced directory: ${d}/`);
  }

  // 2. Validate with web-ext lint
  console.log('\n[2] Validating Firefox Manifest V3 via Mozilla web-ext linter...');
  try {
    const lintOutput = execSync('npx web-ext lint --source-dir extension/firefox', {
      cwd: ROOT,
      encoding: 'utf8'
    });
    console.log(lintOutput);
  } catch (err) {
    console.error('Lint output:', err.stdout || err.message);
    if ((err.stdout || '').includes('errors          0')) {
      console.log('    (Lint passed with 0 errors)');
    } else {
      throw new Error('web-ext lint failed with errors');
    }
  }

  // 3. Package with web-ext build
  console.log('\n[3] Building Firefox Extension ZIP package...');
  const zipDest = path.join(CANDIDATE_DIR, 'artifacts');
  if (!fs.existsSync(zipDest)) fs.mkdirSync(zipDest, { recursive: true });

  execSync(`npx web-ext build --source-dir extension/firefox --artifacts-dir "${zipDest}" --overwrite-dest`, {
    cwd: ROOT,
    stdio: 'inherit'
  });

  // Find generated zip
  const zips = fs.readdirSync(zipDest).filter(f => f.endsWith('.zip'));
  if (zips.length === 0) throw new Error('No zip generated by web-ext build');

  const manifest = JSON.parse(fs.readFileSync(path.join(FF_DIR, 'manifest.json'), 'utf8'));
  const extVersion = manifest.version || '1.0.2';

  const generatedZip = path.join(zipDest, zips[0]);
  const targetZipV102 = path.join(CANDIDATE_DIR, `tori-download-manager-firefox-v${extVersion}.zip`);
  const targetZipV101 = path.join(CANDIDATE_DIR, 'tori-download-manager-firefox-v1.0.1.zip');
  fs.copyFileSync(generatedZip, targetZipV102);
  fs.copyFileSync(generatedZip, targetZipV101);
  fs.rmSync(zipDest, { recursive: true, force: true });

  const zipBuf = fs.readFileSync(targetZipV102);
  const zipHash = crypto.createHash('sha256').update(zipBuf).digest('hex').toLowerCase();
  console.log(`    Created: ${path.basename(targetZipV102)} (${zipBuf.length.toLocaleString()} bytes)`);
  console.log(`    SHA-256: ${zipHash}`);

  // Write SHA256SUMS.txt
  const checksumContent = `${zipHash}  ${path.basename(targetZipV102)}\n${zipHash}  ${path.basename(targetZipV101)}\n`;
  fs.writeFileSync(path.join(CANDIDATE_DIR, 'SHA256SUMS.txt'), checksumContent, 'utf8');

  // Copy manifest and README
  fs.copyFileSync(path.join(FF_DIR, 'manifest.json'), path.join(CANDIDATE_DIR, 'manifest.json'));

  const readmeContent = `# TORI Download Manager v1.0.1 — Firefox Extension Release Candidate

**Add-on Name:** TORI Download Manager — Media Interceptor  
**Extension Version:** ${extVersion}  
**Compatible Desktop Application:** TORI Download Manager v1.0.1  
**Gecko Add-on ID:** \`tori-download-manager@toridm.org\`  
**Manifest Version:** 3 (Gecko MV3 Event Page)  
**Strict Minimum Version:** Firefox 142.0+ (Tested on Firefox 159.0.1)  
**Data Collection:** \`none\` (Zero external data transmission; local 127.0.0.1 IPC only)  

---

## 1. Package Contents

- \`tori-download-manager-firefox-v${extVersion}.zip\`: Authoritative Firefox Add-on package for version ${extVersion}.
- \`tori-download-manager-firefox-v1.0.1.zip\`: Legacy filename compatibility mirror.
- \`manifest.json\`: Validated Firefox Manifest V3.
- \`SHA256SUMS.txt\`: Cryptographic SHA-256 checksums.

---

## 2. Temporary Sideloading (Development / Testing)

1. Open Mozilla Firefox.
2. In the URL bar, navigate to: \`about:debugging#/runtime/this-firefox\`
3. Click **Load Temporary Add-on...**
4. Browse to and select:
   - \`release/v1.0.1-firefox-candidate/manifest.json\` (or the packaged \`.zip\`)
5. The extension will appear in the toolbar with full media detection, popup UI, and Native Messaging support.

---

## 3. Permanent Installation (Mozilla Add-ons / AMO Signing)

In accordance with Mozilla Firefox security policies:
- Permanent installation on release builds of Firefox requires an official Mozilla-signed \`.xpi\`.
- To sign for self-distribution:
  \`\`\`bash
  npx web-ext sign --source-dir extension/firefox --api-key=<JWT_ISSUER> --api-secret=<JWT_SECRET>
  \`\`\`
- This candidate is prepared for signing with zero manifest or security linter errors.

---

## 4. Native Messaging Registration (Windows)

The native messaging host manifest for Firefox is located at:
\`%APPDATA%\\tori-download-manager\\com.tori.download_manager.firefox.json\`

Registry key:
\`HKCU\\Software\\Mozilla\\NativeMessagingHosts\\com.tori.download_manager\`
`;

  fs.writeFileSync(path.join(CANDIDATE_DIR, 'README.md'), readmeContent, 'utf8');
  console.log('    Generated README.md and manifest.json in release/v1.0.1-firefox-candidate/');
  console.log('\n--- Build & Packaging Complete! ---');
}

run();

